public class Print {
    // public class' name should be uppercase (Naming Conventions)
	public static void main(String[]args) {
	    System.out.println("My name is A");//normal println()
        System.out.println("2 * 5 = " + (2*5));
        System.out.println("25 / 10 = " + (25/10)); //"integer type"
        System.out.println("25 / 10 = " + (25/10.0));
        System.out.println("25 / 10 = " + (25.0/10));
        System.out.println("25 / 10 = " + (25.0/10.0) + "\n");
        //the bottom 3s are "float type"
	}
}
