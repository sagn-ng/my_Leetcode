public class ForEach {
    public static void main(String[] args) {
        String[] cars = {"BMW", "Lamborghini", "MacLaren"};
        for (String car : cars){
            System.out.println(car);
        }
        System.out.print("\n");
        int[] arr={10, 20, 30, 40, 50};
        for (int num : arr){
            System.out.println(num);
        }
    }
}